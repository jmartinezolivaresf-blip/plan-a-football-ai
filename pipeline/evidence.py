"""Write docs/AGENT_EVIDENCE.md from the frozen bundle: every decision of each bench and the claims behind it.

    python -m pipeline.evidence

Nothing is typed by hand: texts are the agents' own (placeholders filled from claims), numbers are claim fields.
"""

from __future__ import annotations

from collections import Counter
from pathlib import Path

from agents.validators.text import fill
from contracts import MatchBundle

ROOT = Path(__file__).resolve().parents[1]
BUNDLE = ROOT / "web" / "public" / "match_bundle.json"
OUT = ROOT / "docs" / "AGENT_EVIDENCE.md"


def _claim(claims: dict, cid: str) -> str:
    c = claims.get(cid)
    if c is None:
        return f"`{cid}` (not in bundle)"
    parts = [f"{c.metric.replace('_', ' ')} {c.value}"]
    if c.league_ref is not None:
        parts.append(f"ref {c.league_ref}")
    if c.interval_low is not None:
        parts.append(f"range {c.interval_low} to {c.interval_high}")
    if c.n is not None:
        parts.append(f"n {c.n}")
    return f"`{cid}`: " + ", ".join(parts)


def render(b: MatchBundle) -> str:
    claims = {c.claim_id: c for c in b.claims}
    build = b.eval.get("build", {})
    name = {t: b.squads.teams[t].name for t in b.plans}
    lines = ["# Agent decisions in the demo match", "",
             f"Generated by `python -m pipeline.evidence` from `web/public/match_bundle.json` (season "
             f"{build.get('season_seed')}, match seed {build.get('match_seed')}, commit {build.get('git_commit')}, "
             f"agents: {', '.join(sorted(set(build.get('models', {}).values())))}). Values are inside our "
             "simulator.", ""]
    duel = b.duel
    label = {o.option_id: o.label.en for p in duel.private.values() for o in p.options}
    for team, plan in b.plans.items():
        rep = b.scouting.get(team)
        priv = duel.private[team]
        lines += [f"## {name[team]}", "", f"### Scouting report on {name[rep.opponent] if rep else '?'}", ""]
        for f in rep.findings if rep else []:
            lines.append(f"- {fill(f.headline, claims)}  \n  {_claim(claims, f.claim_id)}")
        lines += ["", f"### Sealed plan: {plan.name.en} (sha256 `{plan.sealed.sha256[:16]}...`)", ""]
        for lever, ids in plan.lever_evidence.items():
            value = getattr(plan.levers, lever)
            lines.append(f"- **{lever} = {value}** because " + "; ".join(_claim(claims, i) for i in ids))
        if plan.valuation:
            lines.append(f"- valuation: {_claim(claims, plan.valuation)}")
        lines += ["- KPIs: " + ", ".join(f"{k.metric.replace('_', ' ')} {k.target}" for k in plan.kpis), ""]
        lines += ["### Half-time", ""]
        lines.append("- options: " + ", ".join(f"{o.label.en} ({o.intent})" for o in priv.options))
        lines.append("- its estimate of the other bench: " + ", ".join(
            f"{e.option.label.en} {round(e.probability * 100)}%" for e in priv.opponent_estimate.options))
        for cid in priv.opponent_estimate.claims:
            lines.append(f"  - {_claim(claims, cid)}")
        r = priv.believed_matrix.readings[team]
        rev = duel.broadcast.revealed[team]
        lines.append(f"- believed matrix: safe pick {label.get(r.safe_pick, r.safe_pick)}, best guess "
                     f"{label.get(r.best_guess, r.best_guess)}, dominant {label.get(r.dominant, r.dominant)}")
        lines.append(f"- sealed choice: **{label[rev.option_id]}** by rule `{rev.rule}` (commit "
                     f"`{priv.choice.sha256[:16]}...`)")
        rg = duel.broadcast.regret[team]
        lines.append(f"- after the reveal: best answer to the other bench was {label[rg.best_response]}; "
                     + _claim(claims, rg.claim_id))
        steps = [t for t in b.traces if t.scope == team]
        status = Counter(t.status for t in steps)
        tools = Counter(t.tool for t in steps if t.tool)
        lines += ["", f"### Trace: {len(steps)} steps ({', '.join(f'{k} {v}' for k, v in sorted(status.items()))})",
                  "", "Tools: " + ", ".join(f"{k} x{v}" for k, v in sorted(tools.items())), ""]
    return "\n".join(lines)


def main() -> int:
    OUT.write_text(render(MatchBundle.model_validate_json(BUNDLE.read_text())))
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
