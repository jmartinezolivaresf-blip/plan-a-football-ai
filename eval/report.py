"""Write eval/results/RESULTS.md from the committed JSON results (no number is typed by hand).

    python -m eval.report
"""

from __future__ import annotations

import json
from pathlib import Path

RESULTS = Path(__file__).resolve().parent / "results"


def _load(name: str) -> dict | None:
    path = RESULTS / name
    return json.loads(path.read_text()) if path.exists() else None


def _ci(d: dict) -> str:
    return f"{d['mean']} (90% CI {d['ci90'][0]} to {d['ci90'][1]}, n {d['n']})"


def render() -> str:
    s = _load("summary.json")
    if s is None:
        return "# Results\n\nRun `make eval` first.\n"
    e1, e2, e3, e4, e7, e8 = s["E1"], s["E2"], s["E3"], s["E4"], s["E7"], s["E8"]
    lines = [
        "# Evaluation results",
        "",
        "Generated by `python -m eval.report` from `eval/results/*.json`. Everything is measured **inside our",
        "simulator** on synthetic data with fictional clubs; nothing here is a claim about real football.",
        "",
        "## Headline",
        "",
        "| Test | What it measures | Result |",
        "|---|---|---|",
        f"| E1 | Scouting reports vs hidden truth, {e1['scouted_teams']} clubs in {len(e1['seasons'])} unseen seasons "
        f"with random trait kinds | precision {e1['precision']}, recall {e1['recall']} ({e1['flagged']} flagged, "
        f"{e1['true_traits']} real traits) |",
        f"| E2 | Monte Carlo noise: R={e2['R'][0]} vs R={e2['R'][1]} for {e2['cells']} lever changes from one "
        f"half-time state | mean abs error {e2['mean_abs_error_xpts']} xPts; 90% CI covers the reference "
        f"{e2['ci90_coverage_of_reference']}; "
        f"sign agreement {e2['sign_agreement']} overall, {e2['sign_agreement_when_reference_is_clear']} on the "
        f"{e2['clear_cells']} cells whose reference interval excludes zero |",
        f"| E3 | Plans that target a real hidden weakness ({e3['plans']} plans) | "
        f"{e3['plans_attacking_a_real_weakness']} vs {e3['random_plan_baseline']} for a blind random plan; levers "
        f"citing claims the staff retrieved "
        f"{e3['levers_citing_served_claims']} |",
        f"| E4 | Grounded text | reports valid at first try {e4['reports_valid_first_try']}; cues dropped by the "
        f"verifier {e4['cues_dropped']}; numbers written by the model {e4['llm_numbers']} (by construction) |",
        f"| E7 | Probability a bench gave to what the other bench really did | {_ci(e7['prob_on_actual_intent'])}; "
        f"uniform guess {e7['uniform_baseline']} |",
        f"| E8 | Half-time regret (xPts lost vs the best answer to the other bench's real choice) | AI "
        f"{_ci(e8['ai_regret'])}; always stay {_ci(e8['always_stay_regret'])}; random "
        f"{_ci(e8['random_choice_regret'])} |",
        "",
        "## E1 by trait kind",
        "",
        "| Trait kind | Flagged | Correct | Real | Precision | Recall |",
        "|---|---|---|---|---|---|",
    ]
    for kind, k in sorted(e1["per_kind"].items()):
        lines.append(f"| {kind} | {k['flagged']} | {k['correct']} | {k['true']} | {k['precision']} | {k['recall']} |")
    lines += [
        "",
        f"## Season statistics of the simulator (evaluation season {s['season_seed']}, 24 matches)",
        "",
        "Targets are the ranges in the plan (Anexo A); they are reported, and only shot volume was calibrated (on dev",
        "seasons, below).",
        "",
        "| Statistic | Value | Target | In range |",
        "|---|---|---|---|",
    ]
    for k, v in s["calibration"].items():
        extra = f" (90% CI {v['ci90'][0]} to {v['ci90'][1]})" if "ci90" in v else ""
        lines.append(f"| {k.replace('_', ' ')} | {v['value']}{extra} | {v['target'][0]} to {v['target'][1]} | "
                     f"{'yes' if v['in_range'] else 'no'} |")
    ad, sim = _load("adaptation_calibration.json"), _load("sim_calibration.json")
    lines += ["", "## Calibrations on dev seasons (never the demo or evaluation seasons)", ""]
    if ad:
        c = ad["chosen"]
        lines += [f"- **Adaptation detector** ({ad['procedure']}; rule: {ad['rule']}): z >= {c['min_z']}, false "
                  f"alarms {c['false_alarm_rate']} per team-match ({ad['null_team_matches']} unchanged team-matches), "
                  f"switches found {c['power']} of {ad['switched_matches']}, median detection delay "
                  f"{c['median_delay_min']} min (90th percentile {c['p90_delay_min']}), change minute error median "
                  f"{c['median_change_minute_error']} (90th percentile {c['p90_change_minute_error']})."]
    if sim:
        c = sim["chosen"]
        lines += [f"- **Shot volume** (rule: {sim['rule']}): shot_logit_offset {c['shot_logit_offset']} gives "
                  f"{c['shots_per_match']} shots and {c['goals_per_match']} goals per match on seasons "
                  f"{', '.join(map(str, sim['seasons']))}."]
    lines += ["", "What these do not show: that the agents would help a real coach, or that the simulator's football",
              "is realistic beyond the statistics above. They show the pipeline is grounded, reproducible and better",
              "than blind baselines inside its own world.", ""]
    return "\n".join(lines)


README = RESULTS.parents[1] / "README.md"
START, END = "<!-- RESULTS_HEADLINE -->", "<!-- /RESULTS_HEADLINE -->"


def headline() -> str:
    """The README's results block: the headline table of RESULTS.md, verbatim."""
    text = render()
    table = text.split("## Headline", 1)[1].split("\n## ", 1)[0].strip()
    return f"{START}\n{table}\n{END}"


def update_readme() -> bool:
    text = README.read_text()
    if START not in text:
        return False
    before, rest = text.split(START, 1)
    after = rest.split(END, 1)[1] if END in rest else rest
    README.write_text(before + headline() + after)
    return True


def main() -> int:
    out = RESULTS / "RESULTS.md"
    out.write_text(render())
    print(f"wrote {out}" + (" and the README results block" if update_readme() else ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
